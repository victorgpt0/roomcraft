// Drawn for any character the font does not have: an empty 5x7 box.
const uint8_t kMissingGlyph[kGlyphHeight] = {0x1F, 0x11, 0x11, 0x11, 0x11, 0x11, 0x1F};

const uint8_t* glyphFor(char c) {
    const int code = static_cast<unsigned char>(c);
    if (code < kFirstChar || code > kLastChar) {
        return kMissingGlyph;
    }
    return kFont[code - kFirstChar];
}

