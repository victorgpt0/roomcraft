void drawText(raster::Canvas& canvas, int x, int y, const std::string& text,
              raster::Color color, int scale) {
    if (scale < 1) {
        scale = 1;
    }
    int penX = x; // left edge of the current character
    for (const char c : text) {
        const uint8_t* glyph = glyphFor(c);
        for (int row = 0; row < kGlyphHeight; ++row) {
            for (int column = 0; column < kGlyphWidth; ++column) {
                // Bit 4 is the leftmost cell, bit 0 the rightmost.
                const bool on = (glyph[row] >> (kGlyphWidth - 1 - column)) & 1;
                if (!on) {
                    continue;
                }
                // One font cell = a scale x scale block of pixels.
                // Canvas::setPixel ignores pixels outside the canvas.
                for (int dy = 0; dy < scale; ++dy) {
                    for (int dx = 0; dx < scale; ++dx) {
                        canvas.setPixel(penX + column * scale + dx, y + row * scale + dy, color);
                    }
                }
            }
        }
        penX += kGlyphAdvance * scale;
    }
}

int textWidth(const std::string& text, int scale) {
    if (scale < 1) {
        scale = 1;
    }
    if (text.empty()) {
        return 0;
    }
    // Every character advances by 6 cells; the last one has no gap after it.
    return (static_cast<int>(text.size()) * kGlyphAdvance - 1) * scale;
}

int textHeight(int scale) {
    return kGlyphHeight * (scale < 1 ? 1 : scale);
}

